args <- commandArgs(trailingOnly = TRUE)
raiz <- if (length(args)) args[[1]] else getwd()
arquivo <- file.path(raiz, "R", "graficos.R")
if (!file.exists(arquivo)) stop("Os graficos e a animacao do exemplo ainda nao foram implementados.")
.libPaths(c(file.path(raiz, ".biblioteca"), .libPaths()))
source(file.path(raiz, "R", "modelo.R"), encoding = "UTF-8")
source(arquivo, encoding = "UTF-8")
modelo <- preparar_dados(datasets::penguins)
estados <- montar_estados(modelo)
stopifnot(nrow(estados$pontos) == 2L * nrow(modelo$dados))
for (etapa in levels(estados$pontos$etapa)) {
  parte <- estados$pontos[estados$pontos$etapa == etapa, ]
  parte <- parte[order(parte$id), ]
  stopifnot(identical(parte$id, modelo$dados$id))
  stopifnot(identical(parte$bill_len, modelo$dados$bill_len))
  stopifnot(identical(parte$bill_dep, modelo$dados$bill_dep))
}
geral <- criar_grafico(modelo, separar = FALSE)
especies <- criar_grafico(modelo, separar = TRUE)
stopifnot(inherits(geral, "ggplot"), inherits(especies, "ggplot"))
a <- ggplot2::ggplot_build(geral)
b <- ggplot2::ggplot_build(especies)
stopifnot(identical(a$layout$panel_params[[1]]$x.range, b$layout$panel_params[[1]]$x.range))
stopifnot(identical(a$layout$panel_params[[1]]$y.range, b$layout$panel_params[[1]]$y.range))
stopifnot(nrow(a$data[[1]]) == nrow(modelo$dados))
stopifnot(nrow(b$data[[1]]) == nrow(modelo$dados))
animacao <- montar_animacao(modelo)
stopifnot(inherits(animacao, "gganim"))
cat("PASSOU: pontos fixos, eixos identicos, graficos e objeto gganimate validos.\n")
