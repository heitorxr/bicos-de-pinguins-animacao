args <- commandArgs(trailingOnly = TRUE)
raiz <- if (length(args)) args[[1]] else getwd()
arquivo <- file.path(raiz, "R", "modelo.R")
if (!file.exists(arquivo)) stop("O modelo estatistico do exemplo ainda nao foi implementado.")
source(arquivo, encoding = "UTF-8")

modelo <- preparar_dados(datasets::penguins)
stopifnot(nrow(modelo$dados) == 342L)
stopifnot(modelo$excluidos == 2L)
stopifnot(identical(sort(unique(as.character(modelo$dados$species))),
                    c("Adelie", "Chinstrap", "Gentoo")))
stopifnot(modelo$r_geral < 0)
stopifnot(nrow(modelo$por_especie) == 3L)
stopifnot(all(modelo$por_especie$r > 0))
stopifnot(sum(modelo$por_especie$n) == nrow(modelo$dados))
stopifnot(length(unique(modelo$dados$id)) == nrow(modelo$dados))
